export type TranslationKey = keyof typeof messages;

type LocaleContextValue = { locale: Locale; setLocale: (locale: Locale) => void; t: (key: TranslationKey) => string };
const LocaleContext = createContext<LocaleContextValue | null>(null);

function initialLocale(): Locale {
  try { return localStorage.getItem(localeStorageKey) === 'hi' ? 'hi' : 'en'; }
  catch { return 'en'; }
}

export function LocaleProvider({ children }: { children: ReactNode }) {
  const [locale, setCurrentLocale] = useState<Locale>(initialLocale);
  function setLocale(next: Locale) {
    setCurrentLocale(next);
    try { localStorage.setItem(localeStorageKey, next); } catch { /* Continue without persistence when storage is unavailable. */ }
  }
  const value = useMemo<LocaleContextValue>(() => ({ locale, setLocale, t: (key) => messages[key][locale] }), [locale]);
  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>;
}

export function useLocale(): LocaleContextValue {
  const context = useContext(LocaleContext);
  if (!context) throw new Error('useLocale must be used within a LocaleProvider.');
  return context;
}

export function LanguageSwitcher({ className = '' }: { className?: string }) {
  const { locale, setLocale } = useLocale();
  return <div className={`language-switcher ${className}`.trim()} role="group" aria-label={locale === 'hi' ? 'भाषा' : 'Language'}>
    <button type="button" aria-label="English" aria-pressed={locale === 'en'} onClick={() => setLocale('en')}>EN</button>
    <button type="button" aria-label="हिन्दी" aria-pressed={locale === 'hi'} onClick={() => setLocale('hi')}>हिंदी</button>
  </div>;
}
